import { useLayoutEffect } from "react";
import { act, render, renderHook, waitFor } from "@testing-library/react";
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { useParticipationSubmit } from "./use-participation-submit";
const state = vi.hoisted(() => ({ owner: "owner-a", generation: 1, token: "token" as string | Promise<string> }));
vi.mock("@privy-io/react-auth", () => ({ usePrivy: () => ({ ready: true, authenticated: true, user: { id: state.owner }, getAccessToken: async () => state.token }) }));
vi.mock("@/components/byus-session-provider", () => ({ useByUsSession: () => ({ ready: true, ownerId: state.owner, generation: state.generation }) }));
const notify = vi.hoisted(() => vi.fn());
vi.mock("@/components/fan-ui/fan-activity-updates", () => ({ notifyFanActivityUpdated: notify }));
const missionId = "11111111-1111-4111-8111-111111111111";
const sourceId = "22222222-2222-4222-8222-222222222222";
const storageKey = () => `byus:live-participation:${state.owner}:show:${missionId}`;
const success = () => Response.json({ missionId, sourceId, state: "pending", awardedPoints: 0, replayed: false });
beforeEach(() => { sessionStorage.clear(); state.owner = "owner-a"; state.generation = 1; state.token = "token"; notify.mockClear(); });
afterEach(() => vi.unstubAllGlobals());
describe("participation intent recovery", () => {
  it("persists before POST, prevents double clicks, and replays the full original request after reload", async () => {
    let resolve!: (response: Response) => void;
    const fetcher = vi.fn().mockImplementationOnce(() => new Promise<Response>(done => { resolve = done; }));
    vi.stubGlobal("fetch", fetcher);
    const done = vi.fn(), first = renderHook(() => useParticipationSubmit("show", missionId, done));
    let request!: Promise<void>;
    act(() => { request = first.result.current.submit({ kind: "text", text: "Keep my original story", uploadIds: [] }); void first.result.current.submit({ kind: "text", text: "duplicate", uploadIds: [] }); });
    await waitFor(() => expect(fetcher).toHaveBeenCalledTimes(1));
    const original = JSON.parse(sessionStorage.getItem(storageKey())!);
    expect(JSON.parse(fetcher.mock.calls[0][1].body)).toEqual(original);
    await act(async () => { resolve(Response.json({ error: { code: "UNAVAILABLE" } }, { status: 503 })); await request; });
    expect(first.result.current.error).toBe("UNKNOWN");
    first.unmount();
    fetcher.mockResolvedValueOnce(success());
    const second = renderHook(() => useParticipationSubmit("show", missionId, done));
    expect(second.result.current.pending).toEqual(original);
    await act(async () => { await second.result.current.submit({ kind: "text", text: "changed after reload", uploadIds: [] }); });
    expect(JSON.parse(fetcher.mock.calls[1][1].body)).toEqual(original);
    expect(sessionStorage.getItem(storageKey())).toBeNull();
    expect(done).toHaveBeenCalledTimes(1);
    expect(notify).toHaveBeenCalledWith("owner-a");
  });
  it("allows a corrected quiz only after a definite rejection", async () => {
    const questionId = "33333333-3333-4333-8333-333333333333";
    const fetcher = vi.fn().mockResolvedValueOnce(Response.json({ error: { code: "LIVE_PARTICIPATION_QUIZ_INCORRECT" } }, { status: 409 })).mockResolvedValueOnce(success());
    vi.stubGlobal("fetch", fetcher);
    const { result } = renderHook(() => useParticipationSubmit("show", missionId, vi.fn()));
    await act(async () => { await result.current.submit({ kind: "quiz", answers: [{ questionId, optionIds: [missionId] }] }); });
    expect(result.current.error).toContain("INCORRECT");
    expect(result.current.pending).toBeNull();
    await act(async () => { await result.current.submit({ kind: "quiz", answers: [{ questionId, optionIds: [sourceId] }] }); });
    const [first, second] = fetcher.mock.calls.map(call => JSON.parse(call[1].body));
    expect(second.requestKey).not.toBe(first.requestKey);
    expect(second.payload.answers[0].optionIds).toEqual([sourceId]);
  });
  it("keeps an ambiguous successful response recoverable", async () => {
    vi.stubGlobal("fetch", vi.fn(async () => Response.json({ missionId, state: "approved" })));
    const { result } = renderHook(() => useParticipationSubmit("show", missionId, vi.fn()));
    await act(async () => { await result.current.submit({ kind: "reservation" }); });
    expect(result.current.error).toBe("UNKNOWN");
    expect(result.current.pending?.payload).toEqual({ kind: "reservation" });
  });
  it("isolates owners and ignores a late response after switching accounts", async () => {
    let resolve!: (response: Response) => void;
    vi.stubGlobal("fetch", vi.fn(() => new Promise<Response>(done => { resolve = done; })));
    const done = vi.fn(), { result, rerender } = renderHook(() => useParticipationSubmit("show", missionId, done));
    let request!: Promise<void>;
    act(() => { request = result.current.submit({ kind: "reservation" }); });
    await waitFor(() => expect(resolve).toBeDefined());
    const previousKey = storageKey();
    state.owner = "owner-b"; state.generation += 1; rerender();
    expect(result.current.pending).toBeNull();
    await act(async () => { resolve(success()); await request; });
    expect(done).not.toHaveBeenCalled();
    expect(notify).not.toHaveBeenCalled();
    expect(sessionStorage.getItem(previousKey)).not.toBeNull();
  });
  it("does not send when the intent cannot be stored", async () => {
    const fetcher = vi.fn(); vi.stubGlobal("fetch", fetcher);
    vi.stubGlobal("sessionStorage", { getItem: () => null, setItem: () => { throw Error("Full"); } });
    const { result } = renderHook(() => useParticipationSubmit("show", missionId, vi.fn()));
    await act(async () => { await result.current.submit({ kind: "reservation" }); });
    expect(fetcher).not.toHaveBeenCalled();
    expect(result.current.error).toBe("INVALID");
  });
  it("does not send the old owner's private text with a token resolved during the next owner's layout", async () => {
    let resolveToken!: (token: string) => void;
    state.token = new Promise<string>(resolve => { resolveToken = resolve; });
    const fetcher = vi.fn().mockResolvedValue(success());
    vi.stubGlobal("fetch", fetcher);
    const done = vi.fn();
    let operation!: ReturnType<typeof useParticipationSubmit>;
    function Owner() {
      operation = useParticipationSubmit("show", missionId, done);
      useLayoutEffect(() => { if (state.owner === "owner-b") resolveToken("token-for-b"); }, []);
      return null;
    }
    const view = render(<Owner key={state.owner} />);
    let request!: Promise<void>;
    act(() => { request = operation.submit({ kind: "text", text: "A private story", uploadIds: [] }); });
    const previousKey = storageKey();
    state.owner = "owner-b"; state.generation += 1;
    await act(async () => { view.rerender(<Owner key={state.owner} />); });
    await request;
    expect(fetcher).not.toHaveBeenCalled();
    expect(done).not.toHaveBeenCalled();
    expect(notify).not.toHaveBeenCalled();
    expect(sessionStorage.getItem(previousKey)).toContain("A private story");
    expect(sessionStorage.getItem(storageKey())).toBeNull();
  });
});
