export const tarotAlt = (id: number, locale: string = "ko") => deckFor(locale)[id][2];

export function tarotTitle(id: number, locale: string = "ko") {
  const [num, name] = deckFor(locale)[id];
  return `${num} ${name}`.trim();
}
