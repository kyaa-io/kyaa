// Pure helpers for the celebrity name dictionary. Sources and licenses are in README.md next to this file.
export const LICENSE = 'CC0-1.0';
const MAX_NAME = 120;

export function cleanName(value) {
  if (typeof value !== 'string') return null;
  const name = value.normalize('NFC').replace(/\s+/g, ' ').trim();
  if (!name || name.length > MAX_NAME) return null;
  if (/[\u0000-\u001f\u007f<>]/.test(name)) return null;
  if (/^Q\d+$/.test(name)) return null; // Wikidata answers with the item id when a label is missing.
  if (!/\p{L}|\p{N}/u.test(name)) return null;
  return name;
}

const OCCUPATION_CATEGORY = new Map([
  ['Q177220', 'singer'], ['Q488205', 'singer'], ['Q2252262', 'singer'], ['Q639669', 'singer'],
  ['Q33999', 'actor'], ['Q10800557', 'actor'], ['Q10798782', 'actor'],
  ['Q17125263', 'creator'], ['Q15077007', 'creator'],
]);
const CATEGORY_ORDER = ['singer', 'actor', 'creator'];

export function categoryFor({ occupations = [], kpop = false, group = false }) {
  if (kpop || group) return 'idol';
  const found = new Set(occupations.map(id => OCCUPATION_CATEGORY.get(id)).filter(Boolean));
  // Wikidata does not say which occupation comes first, so someone listed as both a singer and an actor gets no tag.
  if (found.has('singer') && found.has('actor')) return null;
  return CATEGORY_ORDER.find(category => found.has(category)) ?? null;
}

function uniqueNames(values) {
  const seen = new Set(), names = [];
  for (const value of values) {
    const name = cleanName(value);
    if (!name || seen.has(name)) continue;
    seen.add(name); names.push(name);
  }
  return names;
}

export function makeEntry({ source, sourceId, ko, en, other, aliases = [], category = null, popularity = 0 }) {
  const name_ko = cleanName(ko), name_en = cleanName(en), name_other = name_ko || name_en ? null : cleanName(other);
  if (!name_ko && !name_en && !name_other) return null;
  return { source, source_id: String(sourceId), name_ko, name_en, name_other, category, popularity: Math.max(0, Math.trunc(popularity) || 0), license: LICENSE, terms: uniqueNames([name_ko, name_en, name_other, ...aliases]) };
}

/** Wikidata wins over the MusicBrainz artist it links to. That artist's names join the Wikidata entry as extra search terms. */
export function mergeSources(wikidata, musicbrainz, linkByMusicbrainzId) {
  const byWikidataId = new Map(wikidata.map(entry => [entry.source_id, entry]));
  const kept = [];
  let mergedCount = 0;
  for (const entry of musicbrainz) {
    const target = byWikidataId.get(linkByMusicbrainzId.get(entry.source_id));
    if (!target) { kept.push(entry); continue; }
    target.terms = uniqueNames([...target.terms, ...entry.terms]);
    mergedCount += 1;
  }
  return { entries: [...wikidata, ...kept], mergedCount };
}

export function buildLoadSql(entries) {
  for (const entry of entries) if (entry.license !== LICENSE) throw new Error(`refusing non-CC0 row ${entry.source}:${entry.source_id}`);
  const rows = JSON.stringify(entries.map(({ source, source_id, name_ko, name_en, name_other, category, popularity, license, terms }) => ({ source, source_id, name_ko, name_en, name_other, category, popularity, license, terms })));
  if (rows.includes('$names$')) throw new Error('data contains the SQL quote tag');
  return `-- Generated by scripts/celebrity-names/fetch.mjs. Wikidata and MusicBrainz core data, CC0-1.0.
-- One transaction. Running it again with the same rows writes nothing. Rows that left the file are removed.
\\set ON_ERROR_STOP on
begin;
set local lock_timeout='5s';
create temp table celebrity_name_load on commit drop as
 select * from jsonb_to_recordset($names$${rows}$names$::jsonb) as x(source text,source_id text,name_ko text,name_en text,name_other text,category text,popularity integer,license text,terms jsonb);
do $$
declare added integer;changed integer;removed integer;terms_added integer;terms_removed integer;total integer;
begin
 with x as(insert into public.celebrity_name_entries(source,source_id,name_ko,name_en,name_other,category,popularity,license)
  select source,source_id,name_ko,name_en,name_other,category,popularity,license from celebrity_name_load
  on conflict(source,source_id)do nothing returning 1)select count(*)into added from x;
 with x as(update public.celebrity_name_entries e set name_ko=l.name_ko,name_en=l.name_en,name_other=l.name_other,category=l.category,popularity=l.popularity,updated_at=clock_timestamp()
  from celebrity_name_load l where e.source=l.source and e.source_id=l.source_id
  and(e.name_ko,e.name_en,e.name_other,e.category,e.popularity) is distinct from(l.name_ko,l.name_en,l.name_other,l.category,l.popularity)returning 1)select count(*)into changed from x;
 with x as(delete from public.celebrity_name_entries e where not exists(select 1 from celebrity_name_load l where l.source=e.source and l.source_id=e.source_id)returning 1)select count(*)into removed from x;
 create temp table celebrity_name_term_load on commit drop as
  select distinct e.id entry_id,public.celebrity_name_key(t.value) term_key
  from celebrity_name_load l join public.celebrity_name_entries e on e.source=l.source and e.source_id=l.source_id cross join lateral jsonb_array_elements_text(l.terms)t
  where length(public.celebrity_name_key(t.value)) between 1 and 120;
 with x as(insert into public.celebrity_name_terms(entry_id,term_key)select entry_id,term_key from celebrity_name_term_load on conflict do nothing returning 1)select count(*)into terms_added from x;
 with x as(delete from public.celebrity_name_terms t where not exists(select 1 from celebrity_name_term_load l where l.entry_id=t.entry_id and l.term_key=t.term_key)returning 1)select count(*)into terms_removed from x;
 select count(*)into total from public.celebrity_name_entries;
 raise notice 'CELEBRITY_NAMES summary %',jsonb_build_object('added',added,'changed',changed,'removed',removed,'termsAdded',terms_added,'termsRemoved',terms_removed,'total',total);
end $$;
commit;
`;
}

export function summarize(entries, extra = {}) {
  const count = predicate => entries.filter(predicate).length;
  const categories = {};
  for (const entry of entries) { const key = entry.category ?? 'none'; categories[key] = (categories[key] ?? 0) + 1; }
  return { entries: entries.length, wikidata: count(entry => entry.source === 'wikidata'), musicbrainz: count(entry => entry.source === 'musicbrainz'), withKorean: count(entry => entry.name_ko), withEnglish: count(entry => entry.name_en), terms: entries.reduce((sum, entry) => sum + entry.terms.length, 0), categories, license: LICENSE, ...extra };
}
